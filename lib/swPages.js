"use client";
// N5: сервис-воркер (public/sw.js) хранит копии страниц оболочки и при повторном входе отдаёт их сразу.
// Тема и «Крупный текст» — это cookie, которые читает сервер (атрибуты на <html>), поэтому после их смены
// просим воркер перекачать сохранённые копии: следующий вход откроется уже в новом виде, без мигания.
export function refreshCachedPages() {
  try {
    navigator.serviceWorker?.controller?.postMessage({ type: "REFRESH_PAGES" });
  } catch {
    // нет воркера (первый визит, режим разработки) — копий тоже нет
  }
}
