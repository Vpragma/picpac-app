// Маска SlimSAM (0/1, w×h) → только внутри рамки с запасом pad (доля стороны рамки): маска не «растекается» по фону
export function clipMaskToBox(bits, w, h, box, pad = 0.08) {
  const bw = box.x1 - box.x0;
  const bh = box.y1 - box.y0;
  const x0 = Math.max(0, Math.floor((box.x0 - bw * pad) * w));
  const x1 = Math.min(w, Math.ceil((box.x1 + bw * pad) * w));
  const y0 = Math.max(0, Math.floor((box.y0 - bh * pad) * h));
  const y1 = Math.min(h, Math.ceil((box.y1 + bh * pad) * h));
  const out = new Uint8Array(w * h);
  for (let y = y0; y < y1; y++) {
    const row = y * w;
    for (let x = x0; x < x1; x++) out[row + x] = bits[row + x] ? 1 : 0;
  }
  return out;
}

// Объединение масок одного размера
export function unionMasks(a, b) {
  if (!a) return b;
  if (!b) return a;
  const out = new Uint8Array(a.length);
  for (let i = 0; i < a.length; i++) out[i] = a[i] || b[i] ? 1 : 0;
  return out;
}

// Запасной вариант без SlimSAM (мало памяти): овал, вписанный в рамку
export function boxMask(box, w, h) {
  const out = new Uint8Array(w * h);
  const cx = ((box.x0 + box.x1) / 2) * w;
  const cy = ((box.y0 + box.y1) / 2) * h;
  const rx = Math.max(1, ((box.x1 - box.x0) / 2) * w);
  const ry = Math.max(1, ((box.y1 - box.y0) / 2) * h);
  for (let y = Math.max(0, Math.floor(cy - ry)); y < Math.min(h, Math.ceil(cy + ry)); y++)
    for (let x = Math.max(0, Math.floor(cx - rx)); x < Math.min(w, Math.ceil(cx + rx)); x++) {
      const dx = (x + 0.5 - cx) / rx;
      const dy = (y + 0.5 - cy) / ry;
      if (dx * dx + dy * dy <= 1) out[y * w + x] = 1;
    }
  return out;
}
