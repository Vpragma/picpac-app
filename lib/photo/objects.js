// Текст после глагола («машину справа», «всех людей») → { classes, word, plural, where } или null
export function objectFromText(text) {
  const tokens = String(text || "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .split(/[^a-zа-я0-9-]+/)
    .filter(Boolean);
  let found = null;
  let plural = false;
  let where = null;
  for (const t of tokens) {
    if (ALL.test(t)) plural = true;
    for (const [re, w] of WHERE) if (re.test(t)) where = w;
    if (found) continue;
    for (const [re, names, say] of WORDS) {
      if (re.test(t)) {
        found = { classes: names.map(id), word: t, say };
        // «-ы/-и» у слов женского рода — это и «одна машина» в родительном падеже: тогда множественное только с «все»
        if (PLURAL.test(t) && !/^(человека|мужчины|женщины|девушки|девочки|бабушки|дедушки|подруги|сумки|чашки|кружки|лодки|бутылки|кошки|собаки|птицы|машины|коровы|овцы|лошади|тачки|ложки|вилки|книги|вазы|раковины|клавиатуры|ракетки|духовки|плиты|морковки|мышки|игрушки|щетки|сумочки|скамейки|лавочки|тарелки|миски|кровати|пиццы)$/.test(t)) plural = true;
        break;
      }
    }
  }
  if (!found) return null;
  return { ...found, plural, where };
}

// Из найденных детектором предметов выбрать нужные: классы, «где», один или все. dets — [{ cls, score, x0..y1 }]
export function pickObjects(dets, { classes, plural = false, where = null } = {}) {
  const list = (dets || []).filter((d) => classes.includes(d.cls) && d.score >= 0.3);
  if (!list.length) return [];
  // Первый класс в списке — главный («машина» — легковая, грузовик — запасной)
  const main = list.filter((d) => d.cls === classes[0]);
  const pool = main.length ? main : list;
  if (plural && !where) return pool;
  const cx = (d) => (d.x0 + d.x1) / 2;
  const cy = (d) => (d.y0 + d.y1) / 2;
  const by = {
    left: (a, b) => cx(a) - cx(b),
    right: (a, b) => cx(b) - cx(a),
    top: (a, b) => cy(a) - cy(b),
    bottom: (a, b) => cy(b) - cy(a),
    center: (a, b) => Math.hypot(cx(a) - 0.5, cy(a) - 0.5) - Math.hypot(cx(b) - 0.5, cy(b) - 0.5),
    big: (a, b) => boxArea(b) - boxArea(a),
    small: (a, b) => boxArea(a) - boxArea(b),
  };
  // Без уточнения — самый заметный: уверенность с поправкой на размер
  const sorted = [...pool].sort(where ? by[where] : (a, b) => b.score * Math.sqrt(boxArea(b)) - a.score * Math.sqrt(boxArea(a)));
  return [sorted[0]];
}

